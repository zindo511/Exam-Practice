-- Bài làm (database.md mục 5, state-machines.md mục 2, ADR-0013).
-- session_id có foreign key vì cùng module; student_id là ID identity_user, không có foreign key (ADR-0007).
-- UNIQUE (session_id, student_id): mỗi học sinh một bài làm cho mỗi kỳ thi (ADR-0010).
-- deadline tính một lần lúc bắt đầu theo giờ server: min(started_at + thời lượng, giờ đóng kỳ thi).
-- submitted_at, correct_count, score rỗng khi đang làm và có giá trị ở mọi trạng thái kết thúc.
-- score theo thang điểm của kỳ thi (max_score tối đa 100), 2 chữ số thập phân (ADR-0016).
-- version cho optimistic locking: học sinh, giáo viên và job có thể cùng ghi (ADR-0013, ADR-0017).
CREATE TABLE exam_attempt (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT                   NOT NULL REFERENCES exam_session (id),
    student_id    BIGINT                   NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline      TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_at  TIMESTAMP WITH TIME ZONE,
    correct_count INTEGER,
    score         NUMERIC(5, 2),
    version       BIGINT                   NOT NULL,
    CONSTRAINT uq_exam_attempt_session_student UNIQUE (session_id, student_id),
    CONSTRAINT ck_exam_attempt_status CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'EXPIRED', 'LOCKED')),
    CONSTRAINT ck_exam_attempt_deadline CHECK (started_at < deadline),
    CONSTRAINT ck_exam_attempt_result CHECK (
        (status = 'IN_PROGRESS') = (submitted_at IS NULL AND correct_count IS NULL AND score IS NULL)),
    CONSTRAINT ck_exam_attempt_score CHECK (score IS NULL OR score >= 0)
);

-- Job chốt bài hết giờ (ADR-0013): tìm bài đang làm đã quá hạn chót.
CREATE INDEX ix_exam_attempt_in_progress_deadline ON exam_attempt (deadline) WHERE status = 'IN_PROGRESS';

-- "Kỳ thi của tôi": bài làm của một học sinh.
CREATE INDEX ix_exam_attempt_student ON exam_attempt (student_id);

-- Đáp án: thực thể con của exam_attempt (@OneToMany, README 6.8). Đổi đáp án là sửa dòng cũ.
-- session_question_id trỏ tới câu trong bản chụp đề của kỳ thi, cùng module nên có foreign key.
CREATE TABLE exam_answer (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id          BIGINT                   NOT NULL REFERENCES exam_attempt (id),
    session_question_id BIGINT                   NOT NULL REFERENCES exam_session_question (id),
    selected_option     SMALLINT                 NOT NULL,
    saved_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_exam_answer_attempt_question UNIQUE (attempt_id, session_question_id),
    CONSTRAINT ck_exam_answer_selected_option CHECK (selected_option >= 0)
);
