-- Học sinh đã nhập mã tham gia kỳ thi (database.md mục 5, ADR-0010).
-- session_id có foreign key vì cùng module; student_id là ID identity_user, không có foreign key (ADR-0007).
-- UNIQUE (session_id, student_id): mỗi học sinh một dòng trong mỗi kỳ thi; nhập mã lần nữa không tạo dòng mới.
CREATE TABLE exam_participant (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT                   NOT NULL REFERENCES exam_session (id),
    student_id BIGINT                   NOT NULL,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_exam_participant_session_student UNIQUE (session_id, student_id)
);

-- Trang "Kỳ thi của tôi": các kỳ thi một học sinh đã tham gia.
CREATE INDEX ix_exam_participant_student ON exam_participant (student_id);

-- Các lần nhập sai mã, để chặn khi sai quá 5 lần trong 15 phút (ADR-0010).
-- Dòng cũ hơn 30 phút không còn ảnh hưởng và có thể xóa định kỳ.
CREATE TABLE exam_join_failure (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT                   NOT NULL,
    failed_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_exam_join_failure_student ON exam_join_failure (student_id, failed_at DESC);
