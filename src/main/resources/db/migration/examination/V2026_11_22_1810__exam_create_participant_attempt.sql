-- Tham gia kỳ thi và bài làm (database.md mục 5, state-machines.md mục 2).
-- student_id là ID identity_user, không có foreign key xuyên module (ADR-0007).
-- session_id trỏ tới exam_session trong cùng module nên có foreign key.

-- Có dòng là đã tham gia (state-machines.md mục 4); mỗi học sinh tham gia một kỳ thi một lần.
CREATE TABLE exam_participant (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT                   NOT NULL REFERENCES exam_session (id),
    student_id BIGINT                   NOT NULL,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_exam_participant_session_student UNIQUE (session_id, student_id)
);

-- Bài làm. MVP mỗi học sinh một bài cho mỗi kỳ thi (ADR-0010), chặn ngay ở tầng database.
-- deadline tính một lần lúc bắt đầu: min(started_at + thời lượng, end_at của kỳ thi) (ADR-0013).
-- correct_count và score rỗng khi đang làm, có giá trị ở cả ba trạng thái kết thúc (ADR-0016).
-- version cho optimistic locking: học sinh, giáo viên và job cùng ghi.
CREATE TABLE exam_attempt (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT                   NOT NULL REFERENCES exam_session (id),
    student_id    BIGINT                   NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline      TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_at  TIMESTAMP WITH TIME ZONE,
    correct_count INTEGER,
    score         NUMERIC(4, 2),
    version       BIGINT                   NOT NULL,
    CONSTRAINT uq_exam_attempt_session_student UNIQUE (session_id, student_id),
    CONSTRAINT ck_exam_attempt_status CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'EXPIRED', 'LOCKED')),
    CONSTRAINT ck_exam_attempt_deadline CHECK (started_at <= deadline),
    CONSTRAINT ck_exam_attempt_result CHECK (
        (status = 'IN_PROGRESS' AND submitted_at IS NULL AND correct_count IS NULL AND score IS NULL)
        OR (status <> 'IN_PROGRESS' AND submitted_at IS NOT NULL AND correct_count >= 0
            AND score BETWEEN 0 AND 10))
);

-- Job chốt bài hết giờ: bài IN_PROGRESS có deadline đã qua (ADR-0013).
CREATE INDEX ix_exam_attempt_status_deadline ON exam_attempt (status, deadline);
-- Lịch sử bài làm của học sinh.
CREATE INDEX ix_exam_attempt_student ON exam_attempt (student_id);

-- Đáp án: thực thể con của exam_attempt (@OneToMany, README 6.8). Mỗi câu một đáp án; đổi đáp án
-- là sửa dòng cũ, bỏ chọn là xóa dòng.
CREATE TABLE exam_answer (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id          BIGINT                   NOT NULL REFERENCES exam_attempt (id),
    session_question_id BIGINT                   NOT NULL REFERENCES exam_session_question (id),
    selected_option     SMALLINT                 NOT NULL,
    saved_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_exam_answer_attempt_question UNIQUE (attempt_id, session_question_id),
    CONSTRAINT ck_exam_answer_selected_option CHECK (selected_option >= 0)
);
