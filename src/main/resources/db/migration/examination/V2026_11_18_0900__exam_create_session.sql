-- Kỳ thi (database.md mục 5, state-machines.md mục 1).
-- exam_id và teacher_id là ID của design_exam và identity_user, không có foreign key xuyên module (ADR-0007).
-- access_code duy nhất trên toàn bảng: 6 ký tự A-Z, 0-9 (ADR-0010).
-- duration_minutes rỗng tới khi mở kỳ thi (chụp từ đề, ADR-0003).
-- version cho optimistic locking: giáo viên và job có thể cùng mở hoặc đóng một kỳ thi.
CREATE TABLE exam_session (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id          BIGINT                   NOT NULL,
    teacher_id       BIGINT                   NOT NULL,
    title            VARCHAR(200)             NOT NULL,
    access_code      CHAR(6)                  NOT NULL,
    join_open        BOOLEAN                  NOT NULL,
    start_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INTEGER,
    status           VARCHAR(20)              NOT NULL,
    opened_at        TIMESTAMP WITH TIME ZONE,
    closed_at        TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL,
    CONSTRAINT uq_exam_session_access_code UNIQUE (access_code),
    CONSTRAINT ck_exam_session_access_code CHECK (access_code ~ '^[A-Z0-9]{6}$'),
    CONSTRAINT ck_exam_session_status CHECK (status IN ('SCHEDULED', 'OPEN', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_exam_session_time CHECK (start_at < end_at),
    CONSTRAINT ck_exam_session_duration CHECK (duration_minutes IS NULL OR duration_minutes > 0)
);

-- Danh sách kỳ thi của giáo viên, mặc định theo giờ bắt đầu mới nhất trước.
CREATE INDEX ix_exam_session_teacher ON exam_session (teacher_id, start_at DESC);

-- Bản chụp câu hỏi lúc mở kỳ thi (ADR-0003): thực thể con của exam_session (@OneToMany, README 6.8).
-- Chỉ ghi một lần lúc mở, không thay danh sách, nên UNIQUE kiểm tra ngay như bình thường.
-- source_question_id là ID design_question, chỉ để truy vết, không có foreign key xuyên module.
CREATE TABLE exam_session_question (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         BIGINT   NOT NULL REFERENCES exam_session (id),
    position           INTEGER  NOT NULL,
    source_question_id BIGINT   NOT NULL,
    content            TEXT     NOT NULL,
    options_json       TEXT     NOT NULL,
    correct_option     SMALLINT NOT NULL,
    CONSTRAINT uq_exam_session_question_position UNIQUE (session_id, position),
    CONSTRAINT ck_exam_session_question_position CHECK (position >= 1),
    CONSTRAINT ck_exam_session_question_correct_option CHECK (correct_option >= 0)
);
