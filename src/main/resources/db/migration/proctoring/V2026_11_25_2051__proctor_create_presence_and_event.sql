-- Giám sát (database.md mục 6, ADR-0011): chỉ lưu dữ liệu mà proctoring tự có.
-- attempt_id, session_id trỏ tới bảng của examination, student_id là ID identity_user: khác module nên
-- không có foreign key (ADR-0007).

-- Tình trạng hiện tại, mỗi bài làm một dòng; tạo ở heartbeat đầu tiên, các heartbeat sau ghi đè.
-- current_question: vị trí câu đang xem, bắt đầu từ 1; rỗng khi trình duyệt không báo.
CREATE TABLE proctor_presence (
    attempt_id       BIGINT                   PRIMARY KEY,
    session_id       BIGINT                   NOT NULL,
    student_id       BIGINT                   NOT NULL,
    first_seen_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    current_question INTEGER,
    violation_count  INTEGER                  NOT NULL,
    CONSTRAINT ck_proctor_presence_seen CHECK (first_seen_at <= last_seen_at),
    CONSTRAINT ck_proctor_presence_current_question CHECK (current_question IS NULL OR current_question >= 1),
    CONSTRAINT ck_proctor_presence_violation_count CHECK (violation_count >= 0)
);

-- Màn hình giám sát: mọi học sinh của một kỳ thi.
CREATE INDEX ix_proctor_presence_session ON proctor_presence (session_id);

-- Nhật ký, chỉ ghi thêm.
-- occurred_at do trình duyệt báo nên chỉ để tham khảo; mọi so sánh thời gian dùng received_at (giờ server).
CREATE TABLE proctor_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id  BIGINT                   NOT NULL,
    session_id  BIGINT                   NOT NULL,
    student_id  BIGINT                   NOT NULL,
    type        VARCHAR(30)              NOT NULL,
    detail      VARCHAR(500),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_proctor_event_type CHECK (type IN (
        'TAB_HIDDEN', 'TAB_VISIBLE', 'FULLSCREEN_EXIT',
        'DISCONNECTED', 'RECONNECTED',
        'TEACHER_EXTENDED_TIME', 'TEACHER_LOCKED'))
);

-- Polling sự kiện mới của một kỳ thi (?since=).
CREATE INDEX ix_proctor_event_session_received ON proctor_event (session_id, received_at);

-- Nhật ký của một học sinh.
CREATE INDEX ix_proctor_event_attempt_received ON proctor_event (attempt_id, received_at);
