-- Nhật ký giám sát, chỉ ghi thêm (database.md mục 6, ADR-0011, ADR-0019).
-- attempt_id, session_id trỏ tới bảng của examination, student_id là ID identity_user: khác module nên
-- không có foreign key (ADR-0007).
-- occurred_at do trình duyệt báo nên chỉ để tham khảo; mọi so sánh thời gian dùng received_at (giờ server).
CREATE TABLE proctor_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id  BIGINT                   NOT NULL,
    session_id  BIGINT                   NOT NULL,
    student_id  BIGINT                   NOT NULL,
    type        VARCHAR(30)              NOT NULL,
    detail      VARCHAR(500),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_proctor_event_type CHECK (type IN (
        'TAB_HIDDEN', 'TAB_VISIBLE', 'FULLSCREEN_EXIT',
        'TEACHER_EXTENDED_TIME', 'TEACHER_LOCKED'))
);

-- Polling sự kiện mới của một kỳ thi (?since=).
CREATE INDEX ix_proctor_event_session_received ON proctor_event (session_id, received_at);

-- Nhật ký của một học sinh.
CREATE INDEX ix_proctor_event_attempt_received ON proctor_event (attempt_id, received_at);
