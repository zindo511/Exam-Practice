-- Tài khoản người dùng (database.md mục 3).
-- password_hash: BCrypt dài 60 ký tự, để 100 cho thuật toán băm khác sau này.
-- username lưu dạng đã chuẩn hóa (chữ thường, không khoảng trắng hai đầu) nên UNIQUE thường là đủ.
CREATE TABLE identity_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)              NOT NULL,
    password_hash VARCHAR(100)             NOT NULL,
    full_name     VARCHAR(100)             NOT NULL,
    role          VARCHAR(20)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_identity_user_username UNIQUE (username),
    CONSTRAINT ck_identity_user_role CHECK (role IN ('STUDENT', 'TEACHER'))
);
