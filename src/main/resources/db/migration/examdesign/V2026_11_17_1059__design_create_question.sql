-- Câu hỏi trắc nghiệm của giáo viên (database.md mục 4).
-- teacher_id là ID của identity_user nhưng không có foreign key: liên kết giữa module chỉ bằng ID (ADR-0007).
-- options_json: mảng lựa chọn dạng JSON, ví dụ ["A","B","C"]; correct_option là vị trí đáp án đúng, từ 0.
-- archived_at rỗng là đang dùng, có giá trị là đã lưu trữ (xóa mềm, state-machines.md mục 3).
CREATE TABLE design_question (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id     BIGINT                   NOT NULL,
    content        TEXT                     NOT NULL,
    options_json   TEXT                     NOT NULL,
    correct_option SMALLINT                 NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    archived_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_design_question_correct_option CHECK (correct_option >= 0)
);

-- Ngân hàng câu hỏi luôn được lọc theo giáo viên và chỉ lấy câu đang dùng, mới nhất trước.
CREATE INDEX ix_design_question_teacher_active
    ON design_question (teacher_id, created_at DESC)
    WHERE archived_at IS NULL;
