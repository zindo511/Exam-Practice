-- Đề thi của giáo viên (database.md mục 4).
-- teacher_id là ID của identity_user, không có foreign key xuyên module (ADR-0007).
-- archived_at rỗng là đang dùng, có giá trị là đã lưu trữ (state-machines.md mục 3).
CREATE TABLE design_exam (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id       BIGINT                   NOT NULL,
    title            VARCHAR(200)             NOT NULL,
    duration_minutes INTEGER                  NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    archived_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_design_exam_duration CHECK (duration_minutes BETWEEN 1 AND 300)
);

-- Danh sách đề luôn được lọc theo giáo viên và chỉ lấy đề đang dùng, mới nhất trước.
CREATE INDEX ix_design_exam_teacher_active
    ON design_exam (teacher_id, created_at DESC)
    WHERE archived_at IS NULL;

-- Câu hỏi trong đề: thực thể con của design_exam (@OneToMany, README 6.8).
-- Mỗi câu 1 điểm nên không có cột điểm (ADR-0016).
-- Foreign key tới design_exam và design_question được phép vì cùng module.
-- Hai ràng buộc UNIQUE là DEFERRABLE INITIALLY DEFERRED (kiểm tra lúc commit, không phải sau từng
-- câu lệnh): khi thay danh sách câu, Hibernate INSERT dòng mới trước rồi mới DELETE dòng cũ
-- (orphanRemoval), nên giữa chừng có lúc hai dòng cùng (exam_id, position) hoặc (exam_id, question_id).
CREATE TABLE design_exam_question (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id     BIGINT  NOT NULL REFERENCES design_exam (id),
    position    INTEGER NOT NULL,
    question_id BIGINT  NOT NULL REFERENCES design_question (id),
    CONSTRAINT uq_design_exam_question_position UNIQUE (exam_id, position) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_design_exam_question_question UNIQUE (exam_id, question_id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_design_exam_question_position CHECK (position >= 1)
);

-- Kiểm tra "câu hỏi có đang nằm trong đề nào không" trước khi lưu trữ câu hỏi (QUESTION_IN_USE).
CREATE INDEX ix_design_exam_question_question ON design_exam_question (question_id);
